"""Build step: turn src/WebPage.h (the page you edit) into src/WebAssets.h (what the board serves).

Why: the page was 515 KB, 412 KB of it base64 PNGs (logo + shifter-game art).
The board's WebServer sends it in one blocking write over the truck's AP, and on
a phone at range that stalled or got cut off -> "the UI will not load".
Now: every embedded PNG becomes its own binary file served from /img/<name>.png
(cached by the phone, the shifter art only fetched when the game opens) and the
remaining page is gzipped. Runs automatically before every `pio run`
(extra_scripts in platformio.ini) and can be run by hand: python tools/pack_web.py
"""
import base64, gzip, io, os, re

try:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
except NameError:                                  # under SCons __file__ is not set
    Import("env")                                  # noqa: F821
    ROOT = env.subst("$PROJECT_DIR")               # noqa: F821

SRC = os.path.join(ROOT, "src", "WebPage.h")
OUT = os.path.join(ROOT, "src", "WebAssets.h")

def build():
    text = io.open(SRC, encoding="utf-8").read()
    page = re.search(r'R"(\w*)\(([\s\S]*?)\)\1"', text).group(2)
    imgs = []

    def logo(m):
        imgs.append(("logo", base64.b64decode(m.group(1))))
        return 'src="/img/logo.png"'
    page = re.sub(r'src="data:image/png;base64,([A-Za-z0-9+/=]+)"', logo, page, count=1)

    def shimg(m):
        imgs.append((m.group(1), base64.b64decode(m.group(3))))
        return '%s:{%sd:"/img/%s.png"' % (m.group(1), m.group(2), m.group(1))
    page = re.sub(r'(\w+):\{(w:\d+,h:\d+,)d:"data:image/png;base64,([A-Za-z0-9+/=]+)"', shimg, page)
    assert "base64," not in page, "an embedded image was not extracted"

    gz = gzip.compress(page.encode("utf-8"), 9, mtime=0)

    def arr(name, data):
        rows = [",".join("0x%02x" % b for b in data[i:i + 32]) for i in range(0, len(data), 32)]
        return "static const uint8_t %s[%d] PROGMEM = {\n%s\n};\n" % (name, len(data), ",\n".join(rows))

    out = ["// AUTO-GENERATED by tools/pack_web.py from src/WebPage.h - DO NOT EDIT, edit WebPage.h.",
           "// page: %d bytes -> %d gzipped; %d images (%d bytes) served from /img/." %
           (len(page), len(gz), len(imgs), sum(len(d) for _, d in imgs)),
           "#pragma once", "#include <Arduino.h>", "",
           arr("WEB_PAGE_GZ", gz)]
    for n, d in imgs: out.append(arr("WEB_IMG_" + n, d))
    out.append("struct WebImg { const char *path; const uint8_t *data; size_t len; };")
    out.append("static const WebImg WEB_IMGS[] = {")
    for n, d in imgs: out.append('    { "/img/%s.png", WEB_IMG_%s, sizeof(WEB_IMG_%s) },' % (n, n, n))
    out.append("};")
    out.append("static const int WEB_NIMG = %d;" % len(imgs))
    new = "\n".join(out) + "\n"
    old = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if new != old:                                 # unchanged -> no needless rebuild
        io.open(OUT, "w", encoding="utf-8", newline="\n").write(new)
    print("[pack_web] page %d -> %d B gz, %d images %d B" %
          (len(page), len(gz), len(imgs), sum(len(d) for _, d in imgs)))

build()
